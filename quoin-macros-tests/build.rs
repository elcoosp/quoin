//! Build script: records the enabled framework features into `features.txt`
//! so the trybuild tests can assert on (or skip per) the active backend.
//!
//! When the `gpui` feature is on, the crate's own binary — and every
//! trybuild-orchestrated test case, which links the same dependency graph —
//! needs the `libxkbcommon` / `libxkbcommon-x11` linker names to resolve.
//! This script discovers a directory providing them (see `.cargo/config.toml`
//! for the full contract), links the outer crate, and mirrors the search path
//! into a generated `target/tests/.cargo/config.toml` that the inner trybuild
//! cargo discovers on its own. Nothing here is machine-specific or checked in.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let out_dir = env::var("OUT_DIR").unwrap();
    let dest_path = Path::new(&out_dir).join("features.txt");

    let features: Vec<String> = env::vars()
        .filter(|(key, _)| key.starts_with("CARGO_FEATURE_"))
        .map(|(key, _)| key.trim_start_matches("CARGO_FEATURE_").to_lowercase())
        .collect();

    fs::write(&dest_path, features.join(",")).unwrap();

    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_GPUI");
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_LEPTOS");
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_DIOXUS");

    if features.iter().any(|f| f == "gpui") {
        discover_xkbcommon();
    }
}

/// Locates a directory containing `libxkbcommon.so`, links it into this
/// crate, and publishes the search path for trybuild's inner cargo.
fn discover_xkbcommon() {
    // 1. Explicit override (documented escape hatch).
    if let Some(dir) = env::var_os("QUOIN_XKB_LIB_DIR").map(PathBuf::from) {
        if dir.join("libxkbcommon.so").is_file() {
            publish_xkb_dir(&dir);
            return;
        }
        println!(
            "cargo:warning=QUOIN_XKB_LIB_DIR={} does not contain libxkbcommon.so; probing other locations",
            dir.display()
        );
    }

    // 2. pkg-config (the normal dev-package installation).
    if let Ok(output) = std::process::Command::new("pkg-config")
        .args(["--variable=libdir", "xkbcommon"])
        .output()
        && output.status.success()
    {
        let dir = PathBuf::from(String::from_utf8_lossy(&output.stdout).trim());
        if dir.join("libxkbcommon.so").is_file() {
            publish_xkb_dir(&dir);
            return;
        }
    }

    // 3. Common multiarch/system library directories.
    for dir in [
        "/usr/lib/x86_64-linux-gnu",
        "/usr/lib/aarch64-linux-gnu",
        "/usr/lib64",
        "/usr/lib",
        "/usr/local/lib",
    ] {
        let dir = PathBuf::from(dir);
        if dir.join("libxkbcommon.so").is_file() {
            publish_xkb_dir(&dir);
            return;
        }
    }

    // Nothing found: explain the fix instead of failing with a bare
    // `cannot find -lxkbcommon`.
    println!(
        "cargo:warning=GPUI trybuild tests need the xkbcommon development files; \
         install `libxkbcommon-dev` and `libxkbcommon-x11-dev`, or set \
         QUOIN_XKB_LIB_DIR to a directory containing libxkbcommon.so \
         (see .cargo/config.toml)"
    );
}

/// Emits the link-search path for this crate and writes the generated cargo
/// config under `target/tests/` so trybuild's inner cargo invocations (which
/// resolve config by walking up from `target/tests/trybuild/<case>`) find the
/// same path. `cargo test` strips `RUSTFLAGS` from spawned processes, so the
/// env-var route cannot reach the inner cargo; a config file can.
fn publish_xkb_dir(dir: &Path) {
    println!("cargo:rustc-link-search=native={}", dir.display());

    let Some(target_dir) = target_root() else {
        return;
    };
    let tests_cfg = target_dir.join("tests").join(".cargo");
    if fs::create_dir_all(&tests_cfg).is_err() {
        return;
    }
    let generated = format!(
        "# Generated by quoin-macros-tests/build.rs — do not edit or commit.\n\
         # Carries the discovered xkbcommon search path into trybuild's inner\n\
         # cargo invocations (see .cargo/config.toml for the contract).\n\
         [build]\n\
         rustflags = [\"-L\", \"native={}\"]\n",
        dir.display()
    );
    let _ = fs::write(tests_cfg.join("config.toml"), generated);
}

/// Walks up from `OUT_DIR` to the workspace `target/` root.
fn target_root() -> Option<PathBuf> {
    let mut dir = PathBuf::from(env::var("OUT_DIR").ok()?);
    for _ in 0..6 {
        if dir.file_name().is_some_and(|n| n == "target") {
            return Some(dir);
        }
        if !dir.pop() {
            return None;
        }
    }
    None
}
