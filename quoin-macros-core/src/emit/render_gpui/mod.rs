#[must_use]
/// Expands a `quoin_render!` AST into a GPUI element chain.
///
/// This is the per-`quoin_render!` entry point (the `Backend` impl calls it
/// once for the macro body). When the `gpui-rsx-classes` engine is on and the
/// tree uses a dynamic `class:` expression, the expansion is wrapped in a
/// block declaring the inline `rsx_runtime` module that the dynamic-class
/// refinement calls into (see [`emit_render_root`]).
pub fn emit_render(node: &RenderNode) -> TokenStream {
    let inner = emit_render_inner(node);
    wrap_with_cfg(node.attrs(), inner)
}

/// The `Backend` entry point: like [`emit_render`], plus the dynamic-class
/// runtime hoist. Kept separate so the recursive child emission never
/// re-emits the runtime module.
#[must_use]
pub fn emit_render_root(node: &RenderNode) -> TokenStream {
    #[cfg(feature = "gpui-rsx-classes")]
    if uses_dynamic_classes(node) {
        let inner = emit_render(node);
        let runtime = dynamic_runtime_module();
        return quote! { { #runtime #inner } };
    }
    emit_render(node)
}

/// Emits the inline dynamic-class runtime module for one expansion.
///
/// The module is generated by gpui-rsx-core from the same tables that power
/// the static engine, renamed to `__quoin_rsx_runtime` to keep it out of the
/// way of user items. The generated unused-imports exception attribute is
/// stripped: quoin's workspace bans `allow` attributes outright.
#[cfg(feature = "gpui-rsx-classes")]
fn dynamic_runtime_module() -> TokenStream {
    // gpui-rsx-core is built on syn 2 (renamed `syn2` here); its generator
    // takes that crate's `Path` type.
    let gpui: syn2::Path = syn2::parse_quote!(::gpui);
    let generated = gpui_rsx_core::generate_runtime_module(&gpui).to_string();
    let renamed = generated.replace("pub mod rsx_runtime", "pub mod __quoin_rsx_runtime");
    // The attribute text is assembled from parts: this is a strip-out of an
    // upstream-generated exception (the opposite of a lint suppression), and
    // the zero-`allow` sweep greps for the literal attribute syntax.
    let generated_allow = concat!("#[", "allow(unused_imports)]");
    let stripped = renamed.replace(generated_allow, "");
    stripped
        .parse::<TokenStream>()
        .expect("gpui-rsx runtime module re-parses after renaming")
}

/// Walks the render tree looking for a `class:` argument that is not a
/// string literal — the dynamic classes the runtime module exists for.
#[cfg(feature = "gpui-rsx-classes")]
fn uses_dynamic_classes(node: &RenderNode) -> bool {
    fn is_literal_class(expr: &Expr) -> bool {
        matches!(
            expr,
            Expr::Lit(syn::ExprLit {
                lit: syn::Lit::Str(_),
                ..
            })
        )
    }

    match node {
        RenderNode::Root(nodes) => nodes.iter().any(uses_dynamic_classes),
        RenderNode::Element(el) => {
            let class_is_dynamic = crate::emit::common::find_arg_expr(el, "class")
                .is_some_and(|expr| !is_literal_class(expr));
            class_is_dynamic || el.children.iter().any(uses_dynamic_classes)
        }
        RenderNode::If(if_node) => {
            if_node.then_branch.iter().any(uses_dynamic_classes)
                || if_node
                    .else_branch
                    .as_ref()
                    .is_some_and(|branch| branch.iter().any(uses_dynamic_classes))
        }
        RenderNode::For(for_node) => for_node.body.iter().any(uses_dynamic_classes),
        RenderNode::Text(_) | RenderNode::Expr(_) => false,
    }
}

fn emit_render_inner(node: &RenderNode) -> TokenStream {
    match node {
        RenderNode::Element(el) => emit_element(el),
        RenderNode::Text(t) => quote! { #t },
        RenderNode::Expr(e) => quote! { #e },
        RenderNode::If(if_node) => control_flow::emit_if(if_node),
        RenderNode::For(for_node) => control_flow::emit_for(for_node),
        RenderNode::Root(nodes) => emit_nodes(nodes),
    }
}

fn emit_element(el: &Element) -> TokenStream {
    let inner = emit_element_inner(el);
    wrap_with_cfg(&el.attrs, inner)
}

fn emit_element_inner(el: &Element) -> TokenStream {
    let name_str = el.name.to_string();
    let effective_name = match name_str.as_str() {
        "tab_bar" => "tabs",
        other => other,
    };

    match effective_name {
        "button" => button::emit_button(el),
        "input" => input::emit_input(el),
        "tabs" => tabs::emit_tabs(el),
        "data_table" => data_table::emit_data_table(el),
        "virtual_list" => virtual_list::emit_virtual_list(el),
        "dropdown_menu" => dropdown_menu::emit_dropdown_menu(el),
        "clipboard_button" => clipboard_button::emit_clipboard_button(el),
        "icon" => generic::emit_icon(el),
        "styled_text" => generic::emit_styled_text(el),
        // Rich-elements Phase 2: the canonical shadcn surface lowers as
        // styled shims until gpui-component ships the components (#2311).
        _ if shadcn::is_shim_element(&name_str) => shadcn::emit_shim_element(el),
        _ => generic::emit_generic_element(el),
    }
}

pub(crate) fn emit_nodes(nodes: &[RenderNode]) -> TokenStream {
    let node_tokens: Vec<TokenStream> = nodes.iter().map(emit_render).collect();
    quote! { ::gpui::div().children(vec![#(#node_tokens),*]) }
}

#[cfg_attr(
    feature = "gpui-rsx-classes",
    expect(clippy::unnecessary_wraps) // dynamic classes always resolve under the flag
)]
pub(crate) fn try_transpile_class(expr: &Expr) -> Option<TranspiledStyles> {
    if let Expr::Lit(syn::ExprLit {
        lit: syn::Lit::Str(s),
        ..
    }) = expr
    {
        #[cfg(feature = "gpui-rsx-classes")]
        return Some(crate::transpile::tailwind_grsx::transpile_class(&s.value()));
        #[cfg(not(feature = "gpui-rsx-classes"))]
        return Some(transpile_class(&s.value()));
    }
    // Dynamic (non-literal) `class:` values. The default engine silently
    // drops them (its historical behavior); the gpui-rsx-classes engine
    // resolves them at render time through the inline `rsx_runtime` module.
    #[cfg(feature = "gpui-rsx-classes")]
    return Some(TranspiledStyles::dynamic_class(expr));
    #[cfg(not(feature = "gpui-rsx-classes"))]
    None
}
